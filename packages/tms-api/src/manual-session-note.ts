import { PDFDocument, StandardFonts, rgb, type PDFFont } from 'pdf-lib';
import type { Provider, School, SessionRow, Student } from '@white-glove/tms-db';

export type ManualSessionNoteInput = {
  session: SessionRow;
  student?: Student;
  provider?: Provider;
  school?: School;
  providerName: string;
};

/** Regular sessions only: a manual session with no additional service type. */
export function manualSessionNoteApplies(session: Pick<SessionRow, 'additionalServiceType'>): boolean {
  return !String(session.additionalServiceType || '').trim();
}

/** Stable archive id so editing a manual session replaces its note instead of adding another. */
export function manualSessionNoteArchiveId(sessionId: string): string {
  return `manual-note-${sessionId}`;
}

function winAnsi(text: string): string {
  return String(text || '')
    .replace(/[\u2018\u2019]/g, "'")
    .replace(/[\u201c\u201d]/g, '"')
    .replace(/[\u2013\u2014]/g, '-')
    .replace(/\u2026/g, '...')
    .replace(/[^\x09\x0a\x0d\x20-\x7e\u00a0-\u00ff]/g, '?');
}

function wrap(text: string, font: PDFFont, size: number, maxWidth: number): string[] {
  const lines: string[] = [];
  for (const para of winAnsi(text).split(/\r?\n/)) {
    const words = para.split(/\s+/).filter(Boolean);
    if (!words.length) {
      lines.push('');
      continue;
    }
    let line = '';
    for (const word of words) {
      const next = line ? `${line} ${word}` : word;
      if (font.widthOfTextAtSize(next, size) <= maxWidth) {
        line = next;
      } else {
        if (line) lines.push(line);
        line = word;
      }
    }
    if (line) lines.push(line);
  }
  return lines;
}

/**
 * Digital session note for a manually entered regular session.
 * Laid out like a Frontline "Summary of Related Service Session Notes" entry.
 */
export async function buildManualSessionNotePdf(input: ManualSessionNoteInput): Promise<Buffer> {
  const { session, student, school, providerName } = input;
  const doc = await PDFDocument.create();
  const regular = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);
  const pageSize: [number, number] = [612, 792];
  const margin = 54;
  const width = pageSize[0] - margin * 2;
  let page = doc.addPage(pageSize);
  let y = pageSize[1] - margin;

  const ensure = (needed: number) => {
    if (y - needed < margin) {
      page = doc.addPage(pageSize);
      y = pageSize[1] - margin;
    }
  };
  const line = (text: string, opts: { size?: number; font?: PDFFont; gap?: number } = {}) => {
    const size = opts.size || 10.5;
    const f = opts.font || regular;
    for (const row of wrap(text, f, size, width)) {
      ensure(size + 4);
      page.drawText(row, { x: margin, y: y - size, size, font: f, color: rgb(0.1, 0.1, 0.1) });
      y -= size + 4;
    }
    y -= opts.gap ?? 0;
  };
  const field = (label: string, value: string) => {
    const labelText = `${label} `;
    const labelWidth = bold.widthOfTextAtSize(labelText, 10.5);
    const valueRows = wrap(value || '-', regular, 10.5, width - labelWidth);
    valueRows.forEach((row, i) => {
      ensure(16);
      if (i === 0) {
        page.drawText(winAnsi(labelText), { x: margin, y: y - 10.5, size: 10.5, font: bold });
      }
      page.drawText(row, { x: margin + labelWidth, y: y - 10.5, size: 10.5, font: regular });
      y -= 15;
    });
  };

  line('Summary of Related Service Session Notes', { size: 15, font: bold, gap: 2 });
  line('Digital session note generated by TMS from a manually entered session.', { size: 9, gap: 10 });

  const studentName = student ? `${student.firstName} ${student.lastName}`.trim() : '';
  field('Student Name:', studentName);
  if (student?.programId) field('Program Id:', student.programId);
  if (student?.dob) field('DOB:', student.dob);
  field('District / School:', school?.name || student?.programType || '');
  field('Service Provider:', providerName);
  field('Service:', session.serviceType);
  y -= 6;

  const attendanceLabel: Record<string, string> = {
    attended: 'Attended',
    missed: 'Missed',
    makeup: 'Makeup',
    paid_absence: 'Paid absence',
  };
  field('Date of Service:', session.dateOfService);
  if (session.beginTime || session.endTime) {
    field('Time:', `${session.beginTime || ''} - ${session.endTime || ''}`.trim());
  }
  field('Attendance:', attendanceLabel[session.attendance] || session.attendance);
  if (session.cptLabel) field('CPT:', session.cptLabel);
  if (session.location) field('Setting:', session.location);
  if (session.cancelReason) field('Missed reason:', session.cancelReason);
  y -= 6;

  line('Service Provided:', { font: bold });
  line(session.notes || '(no note text)', { gap: 10 });

  ensure(70);
  line('Provider Signature/Credentials', { font: bold });
  if (session.providerSignatureName) {
    const signedAt = session.providerSignedAt ? new Date(session.providerSignedAt) : null;
    const stamp = signedAt && !Number.isNaN(signedAt.getTime())
      ? signedAt.toISOString().replace('T', ' ').slice(0, 16) + ' UTC'
      : '';
    line(`${session.providerSignatureName}${stamp ? `   Signed ${stamp}` : ''}`);
    line('Electronically signed in TMS by typing the provider name.', { size: 8.5 });
  } else {
    line('Not signed (this attendance does not require a signature).', { size: 9 });
  }

  const bytes = await doc.save();
  return Buffer.from(bytes);
}
